"""MCP schema definitions."""

from __future__ import annotations

from collections.abc import Sequence  # noqa: TC003
from typing import Annotated, Any, Literal

from pydantic import Discriminator, Field, HttpUrl, Tag, model_validator

from aclientp.schema.base import AnnotatedObject, Request, Response, Schema
from aclientp.schema.common import EnvVariable  # noqa: TC001
from aclientp.schema.lenient import DefaultOnError, DefaultOnNull  # noqa: TC001


class HttpHeader(AnnotatedObject):
    """An HTTP header to set when making requests to the MCP server."""

    name: str
    """The name of the HTTP header."""

    value: str
    """The value to set for the HTTP header."""


class BaseMcpServer(AnnotatedObject):
    """MCP server base class."""

    name: str
    """Human-readable name identifying this MCP server."""


class HttpMcpServer(BaseMcpServer):
    """HTTP transport configuration.

    Only available when the Agent capabilities indicate `mcp_capabilities.http` is `true`.
    """

    headers: DefaultOnNull[Sequence[HttpHeader]] = Field(default_factory=list)
    """HTTP headers to set when making requests to the MCP server."""

    type: Literal["http"] = Field(default="http", init=False)
    """HTTP transport type."""

    url: HttpUrl
    """URL to the MCP server."""

    def get_headers_dict(self) -> dict[str, str]:
        return {header.name: header.value for header in self.headers}


class SseMcpServer(BaseMcpServer):
    """SSE transport configuration.

    Only available when the Agent capabilities indicate `mcp_capabilities.sse` is `true`.
    """

    headers: DefaultOnNull[Sequence[HttpHeader]]
    """HTTP headers to set when making requests to the MCP server."""

    type: Literal["sse"] = Field(default="sse", init=False)
    """SSE transport type."""

    url: HttpUrl
    """URL to the MCP server."""

    def get_headers_dict(self) -> dict[str, str]:
        return {header.name: header.value for header in self.headers}


class StdioMcpServer(BaseMcpServer):
    """Stdio transport configuration.

    All Agents MUST support this transport.
    """

    args: DefaultOnNull[Sequence[str]]
    """Command-line arguments to pass to the MCP server."""

    # typ: Literal["stdio"] = Field(default="stdio", init=False)
    # """Stdio transport type."""

    command: str
    """Path to the MCP server executable."""

    env: DefaultOnNull[Sequence[EnvVariable]]
    """Environment variables to set when launching the MCP server."""

    def get_env_dict(self) -> dict[str, str]:
        return {env.name: env.value for env in self.env}


McpServerAcpId = str
"""**UNSTABLE**: Identifier of an MCP server provided over ACP."""

McpRequestId = str
"""**UNSTABLE**: Caller-generated identifier for an inner MCP request."""


class AcpMcpServer(BaseMcpServer):
    """**UNSTABLE**: MCP server reachable over the ACP connection itself (``mcp/message``).

    Only available when the Agent capabilities indicate ``mcp_capabilities.acp`` is ``true``.
    """

    type: Literal["acp"] = Field(default="acp", init=False)
    """ACP transport type."""

    server_id: McpServerAcpId
    """Unique identifier for this MCP server, generated by the component providing it."""


_MCP_TRANSPORTS = frozenset({"http", "sse", "acp", "stdio"})


def _mcp_transport(value: Any) -> str | None:
    """Tag of an MCP server: a missing ``type`` means stdio; unknown types match nothing."""
    if isinstance(value, dict):
        tag = value.get("type", "stdio")
    elif isinstance(value, StdioMcpServer):
        tag = "stdio"
    else:
        tag = getattr(value, "type", None)
    return tag if isinstance(tag, str) and tag in _MCP_TRANSPORTS else None


McpServer = Annotated[
    Annotated[HttpMcpServer, Tag("http")]
    | Annotated[SseMcpServer, Tag("sse")]
    | Annotated[AcpMcpServer, Tag("acp")]
    | Annotated[StdioMcpServer, Tag("stdio")],
    Discriminator(_mcp_transport),
]
"""An MCP server the agent should connect to, selected by ``type``.

Only a missing ``type`` or ``"stdio"`` selects :class:`StdioMcpServer`. A known transport
with a malformed payload (``{"type": "http", "url": 42, "command": ...}``) and unknown
transports fail validation instead of falling back to stdio, like the Rust SDK.
"""


class MessageMcpRequest(Request):
    """**UNSTABLE**: An inner MCP request sent to an ``acp`` MCP server via ``mcp/message``.

    Either side may send it, to the side that declared the server.
    """

    server_id: McpServerAcpId
    """The declared ACP MCP server receiving this request."""

    request_id: McpRequestId
    """The caller-generated identifier for the inner MCP request."""

    method: str
    """The inner MCP method name."""

    params: dict[str, Any] | None = None
    """Optional inner MCP params."""

    session_id: str | None = None
    """The session whose work caused this request (the child's ID for a child session's
    work). The Agent SHOULD include it when it knows the session and MUST NOT guess."""

    tool_call_id: DefaultOnError[str | None] = None
    """The tool call in that session this request is part of. Requires ``session_id``."""

    @model_validator(mode="after")
    def _tool_call_needs_session(self) -> MessageMcpRequest:
        if self.tool_call_id is not None and self.session_id is None:
            msg = "toolCallId requires sessionId"
            raise ValueError(msg)
        return self


class MessageMcpNotification(AnnotatedObject):
    """**UNSTABLE**: An inner MCP notification tied to an active inner MCP request."""

    server_id: McpServerAcpId
    """The declared ACP MCP server handling the associated request."""

    request_id: McpRequestId
    """The identifier of the active inner MCP request."""

    method: str
    """The inner MCP method name."""

    params: dict[str, Any] | None = None
    """Optional inner MCP params."""


class McpError(Schema):
    """**UNSTABLE**: A structured inner MCP error. Never an ACP error code."""

    code: int
    """Inner MCP error code."""

    message: str
    """Inner MCP error message."""

    data: Any = None
    """Optional error data."""


class MessageMcpResponse(Response):
    """**UNSTABLE**: Response to ``mcp/message``: exactly one inner MCP outcome.

    Either an opaque ``result`` (which may be JSON null) or an ``error``.
    Receivers prefer ``result`` if both are present.
    """

    result: Any = None
    """The opaque inner MCP result."""

    error: McpError | None = None
    """The inner MCP error."""
